package com.turnypt.core.crypto

import org.bouncycastle.crypto.generators.Argon2BytesGenerator
import org.bouncycastle.crypto.params.Argon2Parameters
import kotlin.math.roundToLong

/**
 * Argon2id key derivation (RFC 9106) via BouncyCastle's lightweight API.
 *
 * The generator is NOT registered as a JCA provider; the platform crypto
 * providers remain untouched.
 *
 * The optional [secret] and [associatedData] inputs exist so that the
 * RFC 9106 test vectors can be reproduced verbatim (see
 * Argon2KeyDerivatorTest). Production callers pass null for both.
 *
 * [maxHeapBytes] is injectable so tests can emulate a small Android heap
 * deterministically (production reads the real Runtime maximum).
 */
class Argon2KeyDerivator(
    private val maxHeapBytes: () -> Long = { Runtime.getRuntime().maxMemory() },
) {

    /**
     * Derives [outputLength] bytes from [passphrase] and [salt].
     *
     * This function is intentionally CPU- and memory-heavy. Callers are
     * responsible for running it off the main thread and for caching the
     * result (wrapped) instead of re-deriving per message.
     *
     * v0.5.1: a pre-flight heap check rejects profiles whose single
     * allocation cannot fit the process heap BEFORE BouncyCastle tries —
     * the resulting [KdfMemoryException] is a graceful, typed error, not
     * the process-killing [OutOfMemoryError] the raw allocation produced
     * (crash reported with the 256 MiB PARANOID preset).
     */
    fun derive(
        passphrase: CharArray,
        salt: ByteArray,
        params: Argon2Params,
        outputLength: Int = CipherAlgorithm.AES_256_GCM.keyLengthBytes,
        secret: ByteArray? = null,
        associatedData: ByteArray? = null,
    ): ByteArray {
        require(salt.size == SALT_LENGTH_BYTES) { "salt must be $SALT_LENGTH_BYTES bytes" }
        require(outputLength in 4..512) { "unsupported output length" }

        val required = Argon2MemoryGuard.requiredHeapBytes(params)
        if (!Argon2MemoryGuard.fits(maxHeapBytes(), params)) {
            throw KdfMemoryException(required)
        }

        val bcParams = Argon2Parameters.Builder(Argon2Parameters.ARGON2_id)
            .withVersion(Argon2Parameters.ARGON2_VERSION_13)
            .withIterations(params.iterations)
            .withMemoryPowOfTwo(params.memoryExponent)
            .withParallelism(params.parallelism)
            .withSalt(salt)
            .apply {
                if (secret != null) withSecret(secret)
                if (associatedData != null) withAdditional(associatedData)
            }
            .build()

        val generator = Argon2BytesGenerator()
        generator.init(bcParams)
        val output = ByteArray(outputLength)
        return try {
            val generated = generator.generateBytes(passphrase, output)
            check(generated == outputLength) { "Argon2id produced $generated bytes" }
            output
        } catch (e: OutOfMemoryError) {
            // The pre-flight passed but the heap was too fragmented or too
            // busy at the exact moment of allocation — same typed error.
            throw KdfMemoryException(required)
        }
    }

    /** Best-effort estimate of derivation cost in milliseconds, for policy UIs. */
    fun estimatedCostMillis(params: Argon2Params, referenceMillisPerGibPass: Double = 2600.0): Long {
        val gib = (params.memoryKib.toDouble() / (1024.0 * 1024.0)).coerceAtLeast(1.0 / 1024.0)
        return (referenceMillisPerGibPass * gib * params.iterations / params.parallelism.coerceAtMost(4))
            .roundToLong().coerceAtLeast(1)
    }

    companion object {
        const val SALT_LENGTH_BYTES = 16
    }
}
