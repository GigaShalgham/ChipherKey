/**
 * The v0.5 semantic extension (success tone). Read via
 * `LocalSemanticColors.current`; provided by [TurnyptTheme].
 */
val LocalSemanticColors = staticCompositionLocalOf { LightSemantic }

private val AppShapes = Shapes(
